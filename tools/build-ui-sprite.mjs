#!/usr/bin/env node
/**
 * Build Sokna's stable icon contract from Tabler Icons outline SVGs.
 *
 * Usage:
 *   node tools/build-ui-sprite.mjs /path/to/@tabler/icons/icons/outline
 *
 * Stable Sokna ids are deliberately kept separate from upstream filenames so
 * saved category icon_key values and existing ui_icon() calls never change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sourceDir = process.argv[2] ? resolve(process.argv[2]) : '';
if (!sourceDir) {
  console.error('Usage: node tools/build-ui-sprite.mjs /path/to/@tabler/icons/icons/outline');
  process.exit(2);
}

const iconMap = new Map(Object.entries({
  coffee:'coffee', search:'search', bell:'bell', check:'check', close:'x', menu:'menu', home:'home', cart:'shopping-cart',
  'chevron-left':'chevron-left', 'chevron-right':'chevron-right', 'chevron-down':'chevron-down', plus:'plus', minus:'minus',
  sparkles:'sparkles', clock:'clock', warning:'alert-triangle', info:'info-circle', calendar:'calendar', dashboard:'dashboard',
  list:'list', tag:'tag', megaphone:'speakerphone', upload:'upload', download:'download', table:'table', message:'message', users:'users',
  device:'device-mobile', chart:'chart-line', archive:'archive', backup:'database-export', refresh:'refresh', undo:'arrow-back-up',
  settings:'settings', operations:'activity', service:'chef-hat', logout:'logout', eye:'eye', edit:'edit', trash:'trash',
  instagram:'brand-instagram', whatsapp:'brand-whatsapp', copy:'copy', share:'share-2', more:'dots', 'eye-off':'eye-off',

  'cup-hot':'mug', snowflake:'snowflake', cake:'cake', breakfast:'egg-fried', food:'tools-kitchen-2', tea:'teapot',
  herbal:'leaf', bean:'coffee', brew:'filter', 'cold-drink':'glass', 'iced-coffee':'cup', mocktail:'glass-cocktail',
  juice:'bottle', sharbat:'glass-full', shake:'milkshake', smoothie:'bubble-tea', 'healthy-drink':'lemon', brunch:'eggs',
  'iranian-food':'bowl-spoon', burger:'burger', pizza:'pizza', pasta:'tools-kitchen-3', sandwich:'bread', salad:'salad',
  appetizer:'bowl', fries:'bucket', 'kids-menu':'baby-carriage', dessert:'ice-cream-2', 'ice-cream':'ice-cream', pastry:'cookie',
  seasonal:'leaf-maple', location:'map-pin', ticket:'ticket', capacity:'users-group', adjust:'adjustments', print:'printer',
  qr:'qrcode', add:'plus', 'arrow-left':'arrow-left', grill:'grill', fried:'meat', seafood:'fish', sushi:'bowl-chopsticks',
  soup:'soup', bakery:'baguette', waffle:'grid-4x4', donut:'circle-dot', chocolate:'chocolate', 'energy-drink':'battery-charging',
  water:'droplet', 'sugar-free':'circle-off', protein:'milk', vegan:'seedling', diet:'apple', sharing:'users-group', combo:'packages',
  sauce:'bottle', retail:'package', gift:'gift', 'hot-dog':'sausage', noodles:'bowl-chopsticks'
}));

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(projectRoot, 'assets/icons/ui-sprite.svg');
const symbols = [];

for (const [stableId, sourceName] of iconMap) {
  const sourcePath = join(sourceDir, `${sourceName}.svg`);
  let svg;
  try {
    svg = readFileSync(sourcePath, 'utf8');
  } catch {
    throw new Error(`Missing Tabler source for icon-${stableId}: ${sourcePath}`);
  }
  const body = svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i)?.[1] || '';
  const children = body
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean)
    .filter(line => !/stroke="none"\s+d="M0 0h24v24H0z"\s+fill="none"/.test(line));
  if (!children.length) throw new Error(`No visible geometry in ${sourcePath}`);
  const forbidden = children.join('').match(/(?:stroke-width|stroke="#|fill="#)/);
  if (forbidden) throw new Error(`Source ${sourcePath} overrides shared icon styling`);
  symbols.push(`  <symbol id="icon-${stableId}" viewBox="0 0 24 24" data-source="tabler:${sourceName}">${children.join('')}</symbol>`);
}

const output = [
  '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" data-icon-family="tabler-outline" data-icon-version="3.46.0" data-sokna-revision="category-optical-2">',
  '  <!-- Generated by tools/build-ui-sprite.mjs. Stable ids are part of Sokna\'s UI contract. -->',
  ...symbols,
  '</svg>',
  ''
].join('\n');

writeFileSync(outputPath, output, 'utf8');
console.log(`Wrote ${iconMap.size} Tabler-based symbols to ${outputPath}`);
